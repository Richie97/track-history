// The landing page on the app's own host.
//
// site/index.html is the landing page, written for the docs site. The Worker
// also serves it at https://trackevolution.app/ to a visitor with no session
// (src/routes/landing.ts), so the brand's own domain answers a search engine,
// an AI assistant or a first-time visitor with the page that says what the app
// is rather than with a sign-in screen. This script derives that copy:
//
//   node tools/landing.mjs        writes the outputs
//   npm run landing:generate      the same
//
// Outputs (generated — never edit them; edit site/ and re-run):
//   src/landing.generated.ts      the page, as a string the Worker serves
//   public/site/site.css          the stylesheet, unchanged
//   public/site/promo-poster.jpg  the video poster, unchanged
//   public/site/analytics.js      the consent banner + tag, its privacy link
//                                 pointed at the docs host
//
// test/unit/landing.test.js fails when a committed output differs from what
// the current site/ produces.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
const DOCS = "https://docs.trackevolution.app";

// Where a signed-out visitor goes to sign in: any path the Worker doesn't
// claim is answered with the app shell, and this is the one the landing page
// and the service worker name.
export const SIGN_IN_PATH = "/login";

// Runs before the page paints. An installed app (standalone) that finds
// itself signed out wants the sign-in screen, not a brochure; and a signed-out
// visitor following a link into the app (#/event/12) keeps that link.
const REDIRECT = `<script>
    if ((window.matchMedia && matchMedia("(display-mode: standalone)").matches) || navigator.standalone || /^#\\//.test(location.hash)) {
      location.replace("${SIGN_IN_PATH}" + location.hash);
    }
  </script>`;

// Each rule must match, or the source changed shape and the build stops.
function swap(html, from, to, label = from) {
  if (!html.includes(from)) throw new Error(`landing: nothing to rewrite for ${label}`);
  return html.split(from).join(to);
}

export function landingHtml(source) {
  let html = source;
  html = swap(html, 'href="./favicon.svg"', 'href="/favicon.svg"');
  html = swap(html, 'src="./favicon.svg"', 'src="/favicon.svg"');
  html = swap(html, 'href="./site.css"', 'href="/site/site.css"');
  html = swap(html, 'src="analytics.js"', 'src="/site/analytics.js"');
  html = swap(html, 'src="./promo-poster.jpg"', 'src="/site/promo-poster.jpg"');
  html = swap(html, 'href="./docs/', `href="${DOCS}/docs/`);
  html = swap(html, 'href="docs/', `href="${DOCS}/docs/`);
  html = swap(html, 'href="./"', 'href="/"');
  // "Open the app" from the app's own front door is the sign-in screen.
  html = swap(html, 'href="https://trackevolution.app"', `href="${SIGN_IN_PATH}"`);
  html = swap(html, '  <link rel="icon"', `  ${REDIRECT}\n  <link rel="manifest" href="/manifest.webmanifest">\n  <link rel="icon"`);
  const left = html.match(/(?:href|src)="(?!https?:|\/|#|mailto:)[^"]*"/);
  if (left) throw new Error(`landing: a relative link survived: ${left[0]}`);
  return html;
}

export function landingAnalytics(source) {
  return swap(
    source,
    'new URL("docs/privacy.html#analytics", document.currentScript.src).href',
    `"${DOCS}/docs/privacy.html#analytics"`,
    "the privacy link",
  );
}

export function landingModule(html) {
  return `// GENERATED by tools/landing.mjs from site/index.html — do not edit.\n// Edit the site page and run \`npm run landing:generate\`.\nexport const LANDING_HTML: string = ${JSON.stringify(html)};\n`;
}

const read = (p, enc = "utf8") => readFileSync(new URL(p, ROOT), enc);

// path → contents, for every generated file.
export function outputs() {
  return {
    "src/landing.generated.ts": landingModule(landingHtml(read("site/index.html"))),
    "public/site/site.css": read("site/site.css"),
    "public/site/analytics.js": landingAnalytics(read("site/analytics.js")),
    "public/site/promo-poster.jpg": read("site/promo-poster.jpg", null),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(new URL("public/site/", ROOT), { recursive: true });
  for (const [path, body] of Object.entries(outputs())) {
    writeFileSync(new URL(path, ROOT), body);
    console.log(`wrote ${path}`);
  }
}
