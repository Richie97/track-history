/**
 * The AI Coach's pure half (#320) against the web implementation: every row of
 * `contracts/logic/ai-coach.json` (generated by `npm run contracts:logic` from
 * `public/js/ai-coach.js`, the fixture the iOS Kit asserts against too), and
 * the parser against the recorded stream `contracts/streams/ai-coach.sse` in
 * every chunking — byte by byte, so inside the multi-byte "…" too.
 */
class AICoachTest {

    private val fixture: JsonObject =
        Json.parseToJsonElement(RepoRoot.path("contracts/logic/ai-coach.json").readText()).jsonObject

    private val contextJson = Json { explicitNulls = false }

    private fun JsonElement?.text(): String? = (this as? JsonPrimitive)?.contentOrNull

    // ---- words -----------------------------------------------------------------

    @Test
    fun `says what the web says`() {
        assertEquals(fixture["name"].text(), AICoach.COACH_NAME)
        assertEquals(fixture["proWhat"].text(), AICoach.COACH_PRO_WHAT)
        assertEquals(fixture["offline"].text(), AICoach.COACH_OFFLINE)
        assertEquals(fixture["disclaimer"].text(), AICoach.COACH_DISCLAIMER)
        val providers = fixture["providers"]!!.jsonArray.map { it.jsonObject }
        assertEquals(providers.size, AICoach.COACH_PROVIDERS.size)
        providers.zip(AICoach.COACH_PROVIDERS).forEach { (p, port) ->
            assertEquals(p["id"].text(), port.id)
            assertEquals(p["name"].text(), port.name)
            assertEquals(p["keyUrl"].text(), port.keyUrl)
            assertEquals(p["placeholder"].text(), port.placeholder)
        }
        for (row in fixture["providerNames"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(row["name"].text(), AICoach.providerName(row["id"].text()))
        }
        val entries = fixture["entries"]!!.jsonObject
        assertEquals(entries.keys.toList(), AICoach.COACH_ENTRIES.keys.toList())
        for ((key, e) in entries) {
            val port = AICoach.COACH_ENTRIES.getValue(key)
            val o = e.jsonObject
            assertEquals(o["button"].text(), port.button, key)
            assertEquals(o["title"].text(), port.title, key)
            assertEquals(o["question"].text(), port.question, key)
            assertEquals(o["saveTo"].text(), port.saveTo, key)
        }
        for (row in fixture["saveLabels"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(row["label"].text(), AICoach.coachSaveLabel(row["entry"].text()!!))
        }
    }

    // ---- the request's context ------------------------------------------------

    /** A fixture id as the JS saw it: a number stays a number (an Int when whole), a string a string. */
    private fun idOf(e: JsonElement?): Any? {
        val p = e as? JsonPrimitive ?: return null
        if (p is JsonNull) return null
        if (p.isString) return p.content
        p.longOrNull?.let { return if (it in Int.MIN_VALUE..Int.MAX_VALUE) it.toInt() else it }
        return p.doubleOrNull
    }

    @Test
    fun `builds the context the web builds, or none`() {
        val rows = fixture["contexts"]!!.jsonArray.map { it.jsonObject }
        assertTrue(rows.size >= 14)
        for (row in rows) {
            val ids = row["ids"]!!.jsonObject
            val got = AICoach.coachContext(
                row["entry"].text()!!,
                eventId = idOf(ids["eventId"]),
                sessionId = idOf(ids["sessionId"]),
                lapId = idOf(ids["lapId"]),
                compareLapId = idOf(ids["compareLapId"]),
                trackId = idOf(ids["trackId"]),
            )
            val expected = row["context"]
            val encoded = got?.let {
                contextJson.encodeToJsonElement(AICoach.CoachContext.serializer(), it)
            } ?: JsonNull
            assertEquals(expected, encoded, "$row")
        }
    }

    @Test
    fun `a temp id here is negative, and is not a server id`() {
        assertEquals(null, AICoach.coachContext("session", eventId = 3, sessionId = -2))
        assertEquals(null, AICoach.coachContext("compare", lapId = -1, compareLapId = 5))
    }

    // ---- errors and the model field ----------------------------------------------

    @Test
    fun `words a refusal as the web does`() {
        for (row in fixture["errorTexts"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(
                row["text"].text(),
                AICoach.coachErrorText(row["status"]!!.jsonPrimitive.int, row["error"].text(), row["provider"].text()),
                "$row",
            )
        }
    }

    @Test
    fun `resolves the model field as the web does`() {
        val models = fixture["models"]!!.jsonArray.map {
            AICoachModel(it.jsonObject["id"].text()!!, it.jsonObject["label"].text()!!)
        }
        for (row in fixture["modelInputs"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(row["model"].text(), AICoach.resolveModelInput(row["text"].text(), models), "$row")
        }
        for (row in fixture["placeholders"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(row["text"].text(), AICoach.modelPlaceholder(row["defaultModel"].text()))
        }
    }

    // ---- drawing a reply ---------------------------------------------------------

    private fun blockJson(b: CoachBlock): JsonElement = when (b) {
        is CoachBlock.Paragraph -> buildJsonObject {
            put("type", JsonPrimitive("p"))
            put("lines", kotlinx.serialization.json.JsonArray(b.lines.map(::JsonPrimitive)))
        }
        is CoachBlock.ListBlock -> buildJsonObject {
            put("type", JsonPrimitive(if (b.ordered) "ol" else "ul"))
            put("items", kotlinx.serialization.json.JsonArray(b.items.map(::JsonPrimitive)))
        }
        is CoachBlock.Heading -> buildJsonObject {
            put("type", JsonPrimitive("h"))
            put("text", JsonPrimitive(b.text))
        }
    }

    @Test
    fun `reads a reply into the blocks the web draws`() {
        for (row in fixture["markdown"]!!.jsonArray.map { it.jsonObject }) {
            val got = kotlinx.serialization.json.JsonArray(AICoach.coachMarkdownBlocks(row["text"].text()).map(::blockJson))
            assertEquals(row["blocks"], got, row["text"].text())
        }
    }

    @Test
    fun `splits bold as the web does`() {
        for (row in fixture["boldRuns"]!!.jsonArray.map { it.jsonObject }) {
            val expected = row["runs"]!!.jsonArray.map {
                AICoach.BoldRun(it.jsonObject["text"].text()!!, it.jsonObject["bold"]!!.jsonPrimitive.booleanOrNull!!)
            }
            assertEquals(expected, AICoach.coachBoldRuns(row["text"].text()), row["text"].text())
        }
    }

    // ---- keeping a reply -----------------------------------------------------------

    private fun dateOf(e: JsonElement?): LocalDate {
        val o = e!!.jsonObject
        return LocalDate.of(o["year"]!!.jsonPrimitive.int, o["month"]!!.jsonPrimitive.int, o["day"]!!.jsonPrimitive.int)
    }

    @Test
    fun `keeps a reply in the notes as the web does`() {
        for (row in fixture["plainText"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(row["plain"].text(), AICoach.coachPlainText(row["text"].text()))
        }
        for (row in fixture["labels"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(row["label"].text(), AICoach.coachNotesLabel(dateOf(row["date"])))
        }
        for (row in fixture["notes"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(
                row["notes"].text(),
                AICoach.appendCoachNote(row["existing"].text(), row["reply"].text()!!, dateOf(row["date"])),
            )
        }
    }

    // ---- the event stream -------------------------------------------------------------

    private fun parse(feed: (AICoach.SseParser) -> Unit): List<Pair<String, JsonElement>> {
        val events = mutableListOf<Pair<String, JsonElement>>()
        val parser = AICoach.createSseParser { e, d -> events += e to d }
        feed(parser)
        parser.end()
        return events
    }

    @Test
    fun `parses every stream in the fixture as the web does`() {
        for (row in fixture["sse"]!!.jsonArray.map { it.jsonObject }) {
            val chunks = row["chunks"]!!.jsonArray.map { it.text()!! }
            val expected = row["events"]!!.jsonArray.map { it.jsonObject["event"].text()!! to it.jsonObject["data"]!! }
            assertEquals(expected, parse { p -> chunks.forEach(p::push) }, "$chunks")
            // The same bytes, one at a time.
            val bytes = chunks.joinToString("").toByteArray()
            assertEquals(expected, parse { p -> bytes.forEach { p.pushBytes(byteArrayOf(it)) } }, "$chunks bytewise")
        }
    }

    private val recorded: ByteArray = RepoRoot.path("contracts/streams/ai-coach.sse").readBytes()

    private fun checkRecorded(events: List<Pair<String, JsonElement>>) {
        assertEquals(listOf("tool") + List(6) { "text" } + "done", events.map { it.first })
        assertEquals("get_session_insights", events[0].second.jsonObject["name"].text())
        val reply = events.filter { it.first == "text" }.joinToString("") { it.second.jsonObject["delta"].text()!! }
        assertTrue(reply.startsWith("**Where the time is.**"))
        assertTrue(reply.endsWith("whether the car is ready for it."))
        assertEquals("end", events.last().second.jsonObject["stop"].text())
    }

    @Test
    fun `parses the recorded stream whole, and in every two-piece split of its bytes`() {
        checkRecorded(parse { it.pushBytes(recorded) })
        for (cut in 0..recorded.size) {
            checkRecorded(
                parse {
                    it.pushBytes(recorded, 0, cut)
                    it.pushBytes(recorded, cut, recorded.size - cut)
                },
            )
        }
    }

    @Test
    fun `parses the recorded stream byte by byte, and with CRLF line endings`() {
        checkRecorded(parse { p -> recorded.forEach { p.pushBytes(byteArrayOf(it)) } })
        val crlf = String(recorded, Charsets.UTF_8).replace("\n", "\r\n").toByteArray()
        checkRecorded(parse { p -> crlf.forEach { p.pushBytes(byteArrayOf(it)) } })
        // The ellipsis in the tool label is three bytes; split inside it.
        val label = parse { p -> recorded.forEach { p.pushBytes(byteArrayOf(it)) } }[0].second.jsonObject["label"].text()
        assertEquals("Analysing the session…", label)
    }
}
